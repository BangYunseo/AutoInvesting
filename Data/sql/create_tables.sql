-- 매수/매도 시점 시장 지표 스냅샷
CREATE TABLE IF NOT EXISTS TB_MARKET_SNAPSHOT (
    SNAPSHOT_ID     SERIAL PRIMARY KEY,
    SNAP_DATE       VARCHAR(20) NOT NULL,
    TICKER          VARCHAR(20) NOT NULL,
    PRICE           NUMERIC,
    POSITION_20D    NUMERIC,
    RSI_14          NUMERIC,
    MACD_VALUE      NUMERIC,
    MACD_SIGNAL     NUMERIC,
    BB_UPPER        NUMERIC,
    BB_LOWER        NUMERIC,
    SIGNAL          VARCHAR(20),
    BUY_PROBABILITY NUMERIC DEFAULT 0,
    SELL_PROBABILITY NUMERIC DEFAULT 0,
    CHART_AI_SCORE  NUMERIC DEFAULT 0,
    FUND_AI_SCORE   NUMERIC DEFAULT 0,
    QUANT_SIGNAL    TEXT DEFAULT '',
    CHART_AI_SIGNAL TEXT DEFAULT '',
    FUND_AI_SIGNAL  TEXT DEFAULT '',
    DATA_SOURCE     TEXT DEFAULT 'REAL',
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 시스템 로그 영구 저장 테이블 (Render 휘발성 파일시스템 대체 — 재시작에도 보존)
CREATE TABLE IF NOT EXISTS TB_SYSTEM_LOG (
    LOG_ID      SERIAL PRIMARY KEY,
    LOG_DATE    VARCHAR(20) NOT NULL,   -- yyyy-MM-dd (날짜별 조회 필터용)
    LOG_TIME    VARCHAR(30) NOT NULL,   -- yyyy-MM-dd HH:mm:ss
    LEVEL       VARCHAR(10) NOT NULL,   -- INFO / WARN / ERROR / FATAL
    MESSAGE     TEXT NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_SYSTEM_LOG_DATE ON TB_SYSTEM_LOG (LOG_DATE);
