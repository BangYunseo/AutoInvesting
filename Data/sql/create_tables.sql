-- 시스템 로그 영구 저장 테이블 (Render 휘발성 파일시스템 대체 — 재시작에도 보존)
CREATE TABLE IF NOT EXISTS TB_SYSTEM_LOG (
    LOG_ID      SERIAL PRIMARY KEY,
    LOG_DATE    VARCHAR(20) NOT NULL,   -- yyyy-MM-dd (날짜별 조회 필터용)
    LOG_TIME    VARCHAR(30) NOT NULL,   -- yyyy-MM-dd HH:mm:ss
    LEVEL       VARCHAR(10) NOT NULL,   -- INFO / WARN / ERROR / FATAL
    MESSAGE     TEXT NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_SYSTEM_LOG_DATE ON TB_SYSTEM_LOG (LOG_DATE);