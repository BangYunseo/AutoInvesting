-- 매수/매도 시점 시장 지표 스냅샷
CREATE TABLE IF NOT EXISTS TB_MARKET_SNAPSHOT (
    SNAPSHOT_ID     SERIAL PRIMARY KEY,
    SNAP_DATE       VARCHAR(20) NOT NULL,
    TICKER          VARCHAR(20) NOT NULL,
    PRICE           NUMERIC,
    POSITION_20D    NUMERIC,
    RSI_14          NUMERIC,
    MACD_VALUE      NUMERIC,
    MACD_SIGNAL     NUMERIC,
    BB_UPPER        NUMERIC,
    BB_LOWER        NUMERIC,
    SIGNAL          VARCHAR(20),
    BUY_PROBABILITY NUMERIC DEFAULT 0,
    SELL_PROBABILITY NUMERIC DEFAULT 0,
    CHART_AI_SCORE  NUMERIC DEFAULT 0,
    FUND_AI_SCORE   NUMERIC DEFAULT 0,
    QUANT_SIGNAL    TEXT DEFAULT '',
    CHART_AI_SIGNAL TEXT DEFAULT '',
    FUND_AI_SIGNAL  TEXT DEFAULT '',
    DATA_SOURCE     TEXT DEFAULT 'REAL',
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

